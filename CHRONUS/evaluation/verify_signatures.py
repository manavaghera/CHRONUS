"""
Keep only closing phrases the persona really said.

The identity card's signature_phrases were generated by an LLM
(06-Testing/generate_identity_card.py), and some never occur in anything
Elon said ("That's basically it.", "First principles, basically."). Mix
Method used to close answers with them. This script searches the persona's
own words (interviews, tweets, quotes in books: services/provenance.py
FIRST_PERSON) for each phrase and writes the ones it finds, with where, to
the card's "signature_phrases_verified". Mix Method only uses those.

    python -m evaluation.verify_signatures            # Elon (models/elon_musk)
    python -m evaluation.verify_signatures --dry-run  # report only
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from services.provenance import FIRST_PERSON, voice_of  # noqa: E402


def _norm(text: str) -> str:
    return " " + re.sub(r"\s+", " ", re.sub(r"[^a-z0-9' ]", " ", text.lower().replace("’", "'"))).strip() + " "


def verify(phrases: list[str], memories: list[dict]) -> tuple[list[dict], list[str]]:
    """(verified [{phrase, memory_id, source_file, source_type, count}], rejected phrases)."""
    own = [(m, _norm(m["text"])) for m in memories if voice_of(m) == FIRST_PERSON]
    verified, rejected = [], []
    for phrase in phrases:
        needle = _norm(phrase.rstrip(".!?"))
        hits = [m for m, text in own if needle in text]
        if hits:
            first = hits[0]
            verified.append({"phrase": phrase, "memory_id": first.get("memory_id", ""), "source_file": first.get("source_file", ""),
                             "source_type": first.get("source_type", ""), "count": len(hits)})
        else:
            rejected.append(phrase)
    return verified, rejected


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--persona", default="elon_musk")
    parser.add_argument("--units", default=str(ROOT / "04-Memory-Units" / "elon_musk_memory_units.jsonl"))
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    card_path = ROOT / "models" / args.persona / "identity_card.json"
    card = json.loads(card_path.read_text(encoding="utf-8"))
    with open(args.units, encoding="utf-8") as f:
        memories = [json.loads(line) for line in f if line.strip()]
    verified, rejected = verify(card.get("signature_phrases", []), memories)
    for v in verified:
        print(f"  [ok]      {v['phrase']!r}  ({v['count']}x, e.g. {v['source_file']})")
    for phrase in rejected:
        print(f"  [never said] {phrase!r}")
    if not args.dry_run:
        card["signature_phrases_verified"] = verified
        card_path.write_text(json.dumps(card, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"Wrote {len(verified)} verified phrases to {card_path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
